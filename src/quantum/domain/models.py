class TradeProposal(BaseModel):
    """Structured proposal generated by SNIPER with tick-grounded ATR geometry."""
    model_config = ConfigDict(frozen=True, validate_assignment=True)

    proposal_id: str = Field(min_length=1)
    pipeline_run_id: str = Field(min_length=1)
    exchange: ExchangeId
    symbol: str
    side: TradeSide
    order_type: OrderType
    reference_mark_price: float = Field(gt=0.0)
    entry_price: float = Field(gt=0.0)
    entry_zone_low: float = Field(gt=0.0)
    entry_zone_high: float = Field(gt=0.0)
    stop_loss: float = Field(gt=0.0)
    take_profit_1: float = Field(gt=0.0)
    take_profit_2: float = Field(gt=0.0)
    tp1_close_pct: float = Field(default=0.50, gt=0.0, le=1.0)
    estimated_reward_risk: float = Field(ge=1.50)
    expected_net_r: float
    prob_tp1_before_sl: float = Field(ge=0.0, le=1.0)
    prob_tp2_before_sl: float = Field(ge=0.0, le=1.0)
    expected_holding_minutes: int = Field(gt=0)
    rationale: str = Field(min_length=1)
    market_regime: MarketRegime
    invalidation_price: float = Field(gt=0.0)
    sniper_model_version: str = Field(min_length=1)
    created_at_ms: int = Field(gt=0)

    @model_validator(mode="after")
    def validate_price_geometry(self) -> "TradeProposal":
        if self.entry_zone_low > self.entry_zone_high:
            raise ValueError(f"entry_zone_low ({self.entry_zone_low}) > entry_zone_high ({self.entry_zone_high})")

        if self.side == TradeSide.LONG:
            if not (self.stop_loss < self.entry_price < self.take_profit_1 < self.take_profit_2):
                raise ValueError(
                    f"Invalid LONG geometry: SL ({self.stop_loss}) < Entry ({self.entry_price}) < "
                    f"TP1 ({self.take_profit_1}) < TP2 ({self.take_profit_2}) violated"
                )
        else:  # SHORT
            if not (self.stop_loss > self.entry_price > self.take_profit_1 > self.take_profit_2):
                raise ValueError(
                    f"Invalid SHORT geometry: SL ({self.stop_loss}) > Entry ({self.entry_price}) > "
                    f"TP1 ({self.take_profit_1}) > TP2 ({self.take_profit_2}) violated"
                )
        return self


class RiskDecision(BaseModel):
    """Deterministic capital protection evaluation produced by Agent 4 (Risk)."""
    model_config = ConfigDict(frozen=True, validate_assignment=True)

    decision_id: str = Field(min_length=1)
    proposal_id: str = Field(min_length=1)
    pipeline_run_id: str = Field(min_length=1)
    decision: AgentAction
    approved_quantity: float = Field(default=0.0, ge=0.0)
    notional_usdt: float = Field(default=0.0, ge=0.0)
    effective_leverage: float = Field(default=0.0, ge=0.0)
    risk_amount_usdt: float = Field(default=0.0, ge=0.0)
    risk_pct_of_equity: float = Field(default=0.0, ge=0.0)
    net_reward_risk: float = Field(default=0.0)
    estimated_fee_usdt: float = Field(default=0.0, ge=0.0)
    estimated_slippage_bps: float = Field(default=0.0, ge=0.0)
    equity_at_eval_usdt: float = Field(default=0.0, ge=0.0)
    checks_passed: List[str] = Field(default_factory=list)
    veto_reasons: List[str] = Field(default_factory=list)
    evaluated_at_ms: int = Field(gt=0)

    @model_validator(mode="after")
    def validate_decision_consistency(self) -> "RiskDecision":
        if self.decision == AgentAction.APPROVED:
            if len(self.veto_reasons) > 0:
                raise ValueError("APPROVED risk decision cannot contain veto_reasons")
            if self.approved_quantity <= 0.0 or self.notional_usdt <= 0.0:
                raise ValueError("APPROVED risk decision must have positive approved_quantity and notional_usdt")
        elif self.decision == AgentAction.REJECTED:
            if len(self.veto_reasons) == 0:
                raise ValueError("REJECTED risk decision must specify at least one veto_reason")
        else:
            raise ValueError(f"Invalid risk decision action: {self.decision}. Must be APPROVED or REJECTED.")
        return self


