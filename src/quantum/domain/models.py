"""Validated domain data contracts for QUANTUM Multi-Agent Trading Desk."""

import re
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from quantum.domain.enums import (
    AgentAction,
    AgentId,
    CandidateCategory,
    ExchangeId,
    InferenceMode,
    MarketRegime,
    OrderType,
    PipelineStage,
    PipelineStatus,
    TradeSide,
)

SYMBOL_REGEX = re.compile(r"^[A-Z0-9]{2,16}(USDT|PERP)$")


class MarketContext(BaseModel):
    """Normalized multi-timeframe market state at candidate evaluation time."""
    model_config = ConfigDict(frozen=True, validate_assignment=True)

    exchange: ExchangeId
    symbol: str
    snapshot_timestamp_ms: int = Field(gt=0)
    last_price: float = Field(gt=0.0)
    mark_price: float = Field(gt=0.0)
    index_price: float = Field(gt=0.0)
    bid1_price: float = Field(gt=0.0)
    ask1_price: float = Field(gt=0.0)
    spread_bps: float = Field(ge=0.0)
    turnover_24h_usdt: float = Field(ge=0.0)
    price_change_24h_pct: float
    funding_rate: float
    next_funding_time_ms: int = Field(gt=0)
    atr_15m: float = Field(gt=0.0)
    atr_1h: float = Field(gt=0.0)
    rvol_15m: float = Field(ge=0.0)
    rsi_15m: float = Field(ge=0.0, le=100.0)
    features: Dict[str, float] = Field(default_factory=dict)

    @field_validator("symbol")
    @classmethod
    def validate_symbol(cls, v: str) -> str:
        v = v.strip().upper()
        if not SYMBOL_REGEX.match(v) and not (v.endswith("USDT") and len(v) >= 5):
            raise ValueError(f"Invalid perpetual contract symbol format: {v}")
        return v

    @model_validator(mode="after")
    def validate_book_spread(self) -> "MarketContext":
        if self.bid1_price > self.ask1_price:
            raise ValueError(
                f"Crossed order book: bid ({self.bid1_price}) cannot exceed ask ({self.ask1_price})"
            )
        return self


class ScannerCandidate(BaseModel):
    """Opportunity discovered by the 4-stage market scanner."""
    model_config = ConfigDict(frozen=True, validate_assignment=True)

    candidate_id: str = Field(min_length=1)
    scan_cycle_id: str = Field(min_length=1)
    exchange: ExchangeId
    symbol: str
    primary_category: CandidateCategory
    secondary_categories: List[CandidateCategory] = Field(default_factory=list)
    directional_bias: TradeSide
    deterministic_score: float = Field(ge=0.0, le=100.0)
    state_hash: str = Field(min_length=16)
    created_at_ms: int = Field(gt=0)
    expires_at_ms: int = Field(gt=0)
    context: MarketContext

    @model_validator(mode="after")
    def validate_ttl(self) -> "ScannerCandidate":
        if self.expires_at_ms < self.created_at_ms:
            raise ValueError("Candidate expires_at_ms must be greater than or equal to created_at_ms")
        return self


